// Converts a number to written English (for dollar amounts up to millions)
function numberToWords(num) {
  if (!num || isNaN(num)) return 'N/A';
  const ones = ['', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine',
    'Ten', 'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen', 'Seventeen', 'Eighteen', 'Nineteen'];
  const tens = ['', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety'];

  function convert(n) {
    if (n === 0) return '';
    if (n < 20) return ones[n] + ' ';
    if (n < 100) return tens[Math.floor(n / 10)] + (n % 10 ? ' ' + ones[n % 10] : '') + ' ';
    if (n < 1000) return ones[Math.floor(n / 100)] + ' Hundred ' + convert(n % 100);
    if (n < 1000000) return convert(Math.floor(n / 1000)) + 'Thousand ' + convert(n % 1000);
    return convert(Math.floor(n / 1000000)) + 'Million ' + convert(n % 1000000);
  }

  const cents = Math.round((num % 1) * 100);
  const dollars = Math.floor(num);
  let result = convert(dollars).trim() + ' Dollars';
  if (cents > 0) result += ' and ' + convert(cents).trim() + ' Cents';
  return result;
}

function formatCurrency(num) {
  if (!num || isNaN(num)) return 'N/A';
  return '$' + Number(num).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

Deno.serve(async (req) => {
  try {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();
    if (!user) return Response.json({ error: 'Unauthorized' }, { status: 401 });

    const { dealId } = await req.json();
    if (!dealId) return Response.json({ error: 'dealId required' }, { status: 400 });

    // Fetch deal, aircraft
    const deals = await base44.entities.Deal.list();
    const deal = deals.find(d => d.id === dealId);
    if (!deal) return Response.json({ error: 'Deal not found' }, { status: 404 });

    let aircraft = null;
    if (deal.aircraft_id) {
      const aircraftList = await base44.entities.Aircraft.list();
      aircraft = aircraftList.find(a => a.id === deal.aircraft_id);
    }

    // Build merge fields
    const yrMakeModel = aircraft
      ? `${aircraft.year} ${aircraft.make} ${aircraft.model}`
      : (deal.aircraft_summary || 'N/A');
    const registration = aircraft?.registration || '';
    const agreedPrice = deal.agreed_price;
    const deposit = deal.deposit_amount;
    const escrowFee = deal.escrow_fee;

    let text = TEMPLATE;
    text = text.replace('[Yr/Make/Model]', yrMakeModel);
    text = text.replace('[Registration]', registration);
    text = text.replace('[Agreed Price Written]', numberToWords(agreedPrice));
    text = text.replace('[Agreed Price $]', formatCurrency(agreedPrice));
    text = text.replace('[Escrow Company]', deal.escrow_company || 'an escrow company');
    text = text.replace('[Escrow Fee]', formatCurrency(escrowFee));
    text = text.replace('[Deposit Written]', numberToWords(deposit));
    text = text.replace('[Deposit $]', formatCurrency(deposit));
    text = text.replace('[Pre-Buy Location]', deal.prebuy_facility || 'a location agreed upon by both the Seller and Buyer');
    text = text.replace('[Seller Name]', deal.seller_name || 'Seller');
    text = text.replace('[Buyer Name]', deal.buyer_name || 'Buyer');

    // Upload as a text file
    const blob = new Blob([text], { type: 'text/plain' });
    const fileName = `Purchase_Agreement_${yrMakeModel.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.txt`;

    const formData = new FormData();
    formData.append('file', blob, fileName);

    const uploadRes = await base44.integrations.Core.UploadFile({ file: blob });
    const fileUrl = uploadRes.file_url;

    // Save URL to deal documents
    const existingDocs = deal.document_urls || [];
    await base44.entities.Deal.update(dealId, {
      document_urls: [...existingDocs, fileUrl]
    });

    return Response.json({ file_url: fileUrl, text });
  } catch (error) {
    return Response.json({ error: error.message }, { status: 500 });
  }
});